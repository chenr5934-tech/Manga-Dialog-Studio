const SKILL_MAP = new Map(AGENT_SKILLS.map((skill) => [skill.id, skill]));

export function getAgentSkill(id: string): AgentSkill | undefined {
  return SKILL_MAP.get(id);
}

// 系统提示词里常驻的技能目录
export function formatSkillCatalog(): string {
  return AGENT_SKILLS.map((skill) => "- " + skill.id + "：" + skill.name + " —— " + skill.summary).join("\n");
}

// 命中用户要求时给出的推荐技能，用于自动预加载
export function suggestSkillsFor(text: string): string[] {
  const picked: string[] = [];
  const hit = (id: string, keywords: string[]) => {
    if (keywords.some((keyword) => text.includes(keyword))) {
      picked.push(id);
    }
  };

  hit("grid-rhythm", ["分镜", "分格", "切", "网格", "几格", "排版", "布局"]);
  hit("panel-composition", ["特写", "远景", "近景", "构图", "圆形", "椭圆", "俯视", "仰视"]);
  hit("bubble-flow", ["气泡", "对话框", "台词", "旁白", "文字", "对白"]);
  hit("eye-path", ["视线", "引导", "阅读", "节奏", "翻页"]);
  hit("gutter-breathing", ["留白", "间隙", "间距", "呼吸"]);
  hit("reference-tracing", ["参考图", "照着", "复刻", "仿照", "这张图"]);
  return Array.from(new Set(picked));
}